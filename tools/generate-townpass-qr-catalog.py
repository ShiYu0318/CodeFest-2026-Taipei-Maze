"""Keep the native scanner allowlist aligned with the web's enabled points."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('townpass', type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
data = json.loads((root / 'app/src/views/station-points.json').read_text())
ids = [point['id'] for points in data['points'].values() for point in points
       if point.get('enabled') is not False]
if len(ids) != len(set(ids)) or any(not re.fullmatch(r'[a-zA-Z0-9_-]+', point) for point in ids):
    raise ValueError('Station point IDs must be unique and safe Dart literals')
content = ('// SPDX-License-Identifier: AGPL-3.0-or-later\n'
           '// Generated by tools/generate-townpass-qr-catalog.py; do not edit.\n'
           'const codefestStationPointIds = <String>{\n' +
           ''.join(f"  '{point}',\n" for point in ids) + '};\n')
target = args.townpass / 'lib/util/codefest_station_points.g.dart'
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Native QR catalog differs from station-points.json; regenerate and refresh qr-entry.patch')
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
print(f'Native QR catalog: {len(ids)} enabled points ({"checked" if args.check else "generated"})')
